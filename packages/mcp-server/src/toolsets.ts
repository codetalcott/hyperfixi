/** The toolset a tool belongs to: its entry above, else `domains` for a registry tool. */
export function toolsetOf(
  name: string,
  isDomainTool: (name: string) => boolean
): ToolsetName | undefined {
  return STATIC_TOOLSETS[name] ?? (isDomainTool(name) ? 'domains' : undefined);
}

/** The toolsets a LOKASCRIPT_MCP_TOOLSETS value turns on (core always), and names it does not know. */
export function parseToolsets(value: string | undefined): {
  enabled: Set<ToolsetName>;
  unknown: string[];
} {
  const enabled = new Set<ToolsetName>(['core']);
  const unknown: string[] = [];
  for (const raw of (value ?? '').split(/[\s,]+/)) {
    const name = raw.trim().toLowerCase();
    if (!name || name === 'core') continue;
    if (name === 'all') TOOLSET_NAMES.forEach(n => enabled.add(n));
    else if ((TOOLSET_NAMES as readonly string[]).includes(name)) enabled.add(name as ToolsetName);
    else unknown.push(raw.trim());
  }
  return { enabled, unknown };
}

/** The tools `tools/list` shows: those whose toolset is enabled. */
export function listedTools<T extends { name: string }>(
  tools: readonly T[],
  enabled: ReadonlySet<ToolsetName>,
  isDomainTool: (name: string) => boolean
): T[] {
  return tools.filter(tool => {
    const toolset = toolsetOf(tool.name, isDomainTool);
    return toolset !== undefined && enabled.has(toolset);
  });
}
